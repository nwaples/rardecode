type oldArchiveEntry struct {
	name string
	err  error // expected when reading the file
}

func TestArchive15OldBlocks(t *testing.T) {
	for _, tc := range []struct {
		name    string
		archive string
		want    []oldArchiveEntry
	}{
		{"file comments, RAR 1.5 compression", rar15Comment, []oldArchiveEntry{{"FILE1.TXT", ErrUnsupportedDecoder}, {"FILE2.TXT", nil}}},
		{"file comments", rar202Comment, []oldArchiveEntry{{"FILE1.TXT", nil}, {"FILE2.TXT", nil}}},
		{"old style subblock", rar2UnixOwner, []oldArchiveEntry{{"file.txt", nil}}},
		{"authenticity information", rar2AuthenticityBlock, nil},
	} {
		t.Run(tc.name, func(t *testing.T) {
			data, err := hex.DecodeString(tc.archive)
			if err != nil {
				t.Fatal(err)
			}
			r, err := NewReader(bytes.NewReader(data))
			if err != nil {
				t.Fatal(err)
			}
			var got []oldArchiveEntry
			for {
				h, err := r.Next()
				if err == io.EOF {
					break
				}
				if err != nil {
					t.Fatalf("Next after %d entries: %v", len(got), err)
				}
				_, err = io.Copy(io.Discard, r)
				got = append(got, oldArchiveEntry{h.Name, err})
			}
			if len(got) != len(tc.want) {
				t.Fatalf("entries = %v, want %v", got, tc.want)
			}
			for i, want := range tc.want {
				if got[i].name != want.name || !errors.Is(got[i].err, want.err) || (want.err == nil) != (got[i].err == nil) {
					t.Errorf("entry %d = %v, want %v", i, got[i], want)
				}
			}
		})
	}
}
